// Generates src/generated/editor-types.ts: JSON schemas of the editor command and
// the timeline model types tool arguments are built from, read from the @opennan/timeline-core sources. A TypeScript module
// rather than a .json import: tsup's declaration bundle would copy an imported JSON
// document into index.d.ts as a value.
// Usage: node scripts/generate-types.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createGenerator } from "ts-json-schema-generator";

const PKG = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CORE = path.resolve(PKG, "../timeline-core");
const OUT = path.join(PKG, "src/generated/editor-types.ts");

// Only types a tool is built from (Task 7); add a root when a tool uses it.
const ROOTS = [
    ["EditorCommand", "src/controller/commands.ts"],
    ["TimelineClip", "src/model/timeline.ts"],
    ["TimelineTrack", "src/model/timeline.ts"],
    ["SceneData", "src/timeline/canvas/types.ts"],
];

function generate() {
    const types = {};
    for (const [type, file] of ROOTS) {
        const schema = createGenerator({
            path: path.join(CORE, file),
            tsconfig: path.join(CORE, "tsconfig.json"),
            type,
            expose: "none",
            topRef: false,
            skipTypeCheck: true,
            // No JSDoc: timeline-core comments cite the files they were copied from and
            // are not tool documentation. Tools describe their own arguments (Task 7).
            jsDoc: "none",
        }).createSchema(type);
        // expose:"none" inlines every named type; only a recursive type would leave a definition behind.
        if (Object.keys(schema.definitions ?? {}).length > 0) {
            throw new Error(`${type} has recursive definitions; the tool schemas expect inlined types`);
        }
        delete schema.$schema;
        delete schema.definitions;
        types[type] = schema;
    }
    const text = [
        "// Generated by packages/mcp-schema/scripts/generate-types.mjs from @opennan/timeline-core. Do not edit.",
        `export type EditorTypeName = ${ROOTS.map(([type]) => JSON.stringify(type)).join(" | ")};`,
        "",
        `export const EDITOR_TYPES: Readonly<Record<EditorTypeName, { [key: string]: unknown }>> = ${JSON.stringify(types, null, 4)};`,
        "",
    ].join("\n");
    return { text, variants: types.EditorCommand.anyOf.length };
}

const { text, variants } = generate();
if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== text) {
        console.error("src/generated/editor-types.ts is out of date: run pnpm --filter @opennan/mcp-schema generate");
        process.exit(1);
    }
    console.log("editor-types: up to date");
} else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, text);
    console.log(`editor-types: wrote ${ROOTS.length} types (EditorCommand: ${variants} variants)`);
}
