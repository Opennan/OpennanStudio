// Renders docs/ai-tool-coverage.md (spec §5.11) from the registry.
import { isOpenNanCapability } from "./capabilities";
import { toolCoverage } from "./registry";
import { PROJECT_PIPELINE_TOOLS } from "./tools/pipelines";
import type { ToolDefinition } from "./types";

function mapping(tool: ToolDefinition): string {
    if (tool.kind === "capability") return `capability \`${tool.capability}\``;
    if (tool.kind === "host") return "editor UI (host)";
    const commands = (tool.commands ?? []).map((c) => (c === "*" ? "any `EditorCommand`" : `\`${c}\``));
    const reads = (tool.reads ?? []).map((r) => `\`${r}()\``);
    return [...commands, ...reads].join(", ");
}

/** Phase 11 capability tools that answer from the host without running a job. */
const HOST_ANSWERS: Readonly<Record<string, string>> = {
    estimate_cost: "plans the run like the editor and asks the routed provider's `price()`; local tools answer free",
    check_generation_status: "the host's AI job book: status, progress, cost, refund, and whether cancel still stops a job",
    list_voices: "the routed speech provider's `voices()`, else unavailable",
};

/** Phase 9b project pipeline tools: OpenNan runs them only on projects stored on its server; Studio projects are local. */
const PIPELINE_ANSWER = "unavailable: OpenNan runs it only on projects stored on OpenNan, and Studio projects stay on the device (host seam `pipelines`, supplied by no current host)";

const STORY_FILM_STEP = "story film: makes what the project's story film is missing on the routed provider, priced first (`estimate_only`, `accept_max_usd`); each result lands in the project's media and on the story";

function phase5(tool: ToolDefinition): string {
    if ((PROJECT_PIPELINE_TOOLS as readonly string[]).includes(tool.name)) return PIPELINE_ANSWER;
    if (tool.name.startsWith("story_film_") && tool.kind === "capability") return STORY_FILM_STEP;
    if (tool.name === "story_film_create") return "offline with `story`; `text` drafts through the routed story writer (`text.generate`), priced first";
    if (tool.kind === "capability") {
        if (HOST_ANSWERS[tool.name]) return HOST_ANSWERS[tool.name]!;
        if (tool.commands?.includes("ai.run")) {
            if (tool.capability === "audio.transcribe") return "runs `ai.run` with engine local (desktop whisper.cpp) or cloud (OpenNan, priced first), else unavailable";
            if (tool.capability === "media.stabilize") return "runs `ai.run` on the desktop app's on-device stabilizer; headless and web: unavailable";
            if (tool.origin === "studio") {
                return "runs `ai.run` on the routed provider after pricing it like the editor (OpenNan by default; signed out: the sign-in guidance); the result lands as one undo step";
            }
            return "runs `ai.run` on the routed provider (OpenNan by default; signed out: the sign-in guidance); the media lands in the project's library";
        }
        return isOpenNanCapability(tool.capability ?? "") ? "unavailable: Connect OpenNan" : "unavailable: needs a provider";
    }
    if (tool.kind === "host") return "desktop/web host; unavailable headless";
    const extra = tool.capabilityFields ? `; \`${tool.capabilityFields.capability}\` fields refused` : "";
    if (tool.commands?.includes("export.start")) {
        return "runs `export.start` on `@opennan/export` when the host has an exporter (headless: `--ffmpeg`), else unavailable";
    }
    if (tool.commands?.includes("export.cancel")) return "runs `export.cancel` on the host's exporter (headless: `--ffmpeg`), else unavailable";
    if (tool.reads?.includes("previewFrame")) return "offline; the image needs a frame renderer (headless: `--ffmpeg`)";
    if (tool.reads?.includes("exportStatus")) return "offline; jobs started by `assemble_video`";
    if (tool.commands?.includes("tracking.run")) return "offline, on the device; needs an editor window that decodes video (headless: unavailable)";
    if (tool.commands?.includes("analysis.run")) return "offline, on the device; needs an audio decoder (editor window, or headless `--ffmpeg`)";
    if (tool.commands?.includes("analysis.fillers")) return "offline; reads the caption word timings";
    return `offline${extra}`;
}

export function renderCoverageMarkdown(): string {
    const retired = new Set<string>(PROJECT_PIPELINE_TOOLS);
    const rows = toolCoverage().map((row) => retired.has(row.name)
        ? { name: row.name, exposed: false as const, reason: "Server-project pipeline; excluded from the default MCP server." } : row);
    const exposed = rows.filter((row) => row.exposed);
    const lines = [
        "# AI tool coverage",
        "",
        "Generated by `pnpm tools:coverage` from `@opennan/mcp-schema`. Do not edit by hand.",
        "",
        "Every tool of the OpenNan editor/chat toolset maps to an editor command (spec §5.1.1), a read API, or a provider capability (spec §5.11).",
        "`packages/mcp/src/handlers/coverage.test.ts` fails when a listed MCP tool has no handler.",
        "",
        `MCP tools: ${exposed.length}. Not exposed: ${rows.length - exposed.length}.`,
        "",
        "| MCP name | Origin | Kind | Command, read API, or capability | Phase 5 behavior |",
        "|---|---|---|---|---|",
    ];
    for (const row of rows) {
        if (row.exposed) {
            lines.push(`| \`${row.name}\` | ${row.tool.origin} | ${row.tool.kind} | ${mapping(row.tool)} | ${phase5(row.tool)} |`);
        } else {
            lines.push(`| \`${row.name}\` | opennan | not exposed | none | ${row.reason} |`);
        }
    }
    return `${lines.join("\n")}\n`;
}
