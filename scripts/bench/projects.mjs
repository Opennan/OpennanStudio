import { templateStyleJson } from "../../packages/timeline-core/dist/text/templates.js";

export const MEDIA_PREFIX = "/bench-media";

const track = (type, index) => ({ type, index, label: "", muted: false, locked: false, visible: true, volume: 1 });
const TRACKS = [track("video", 1), track("video", 2), track("audio", 1), track("text", 1), track("text", 2), track("sticker", 1), track("effect", 1)];

function scene(id, start, duration, patch = {}) {
    return {
        id, order: 0, caption: "", startTime: "0", endTime: "0", startImageUrl: null, endImageUrl: null, videoUrl: null,
        sourceVideoUrl: null, status: "ready", transition: "cut", cardType: "source_clip", duration,
        frameConsistencyScore: null, audioUrl: null, audioText: null, cardConfig: null, timelinePositionSeconds: start || 0.001, ...patch,
    };
}
const clip = (id, input) => optimisticTimelineClipFromInput(input, "bench", id);
const project = (scenes, clips) => ({ project: { aspectRatio: "16:9", musicUrl: null, musicVolume: 1 }, tracks: TRACKS, scenes, clips });

