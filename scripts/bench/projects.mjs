// Fixed export benchmark projects (phase 10c). Plain ExportInput JSON built from timeline-core's built dist
// (run `pnpm build` first), shared by every bench host: native ffmpeg in Node, ffmpeg.wasm and the GPU path in
// Chromium (the playground's ?harness=bench page), and the GPU path in Electron.
//
// (a) "showcase": about 60 s at 1080p, 10 main-track clips with 9 transitions of mixed types, filters, Adjust,
//     3 effects (two clip effects and an effect-track span), animated text, stickers, keyframes, a speed curve,
//     and a picture-in-picture overlay with keyframed motion.
// (b) "stress": the phase 10b 40-scene project (stills and a short video, a filter, Adjust, and a transition on
//     every cut, three overlay clips with looks of their own).
import { optimisticTimelineClipFromInput } from "../../packages/timeline-core/dist/lib/timeline-optimistic.js";
import { serializeAnimationSpec } from "../../packages/timeline-core/dist/motion/animation-spec.js";
import { serializeSpeedCurve, speedCurvePreset } from "../../packages/timeline-core/dist/motion/speed.js";
