// Generates packages/timeline-react/src/i18n/en.ts from the private frontend's
// messages/en.json plus packages/timeline-react/src/i18n/en-overrides.json.
// Usage: node scripts/extract-timeline-messages.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const FULL_NAMESPACES = ["timeline", "canvasTimeline", "clipProperties", "addTrack", "previewPanel", "scenePreview"];
export const PICKED_KEYS = { modals: ["close"], effectsTab: ["parameters"], graphicsTab: ["rendersOnExport"] };

function flatStrings(namespace, section) {
    const out = {};
    for (const [key, value] of Object.entries(section)) {
        if (typeof value !== "string") throw new Error(`${namespace}.${key} is not a string (nested messages are not supported)`);
        out[key] = value;
    }
    return out;
}

export function pickMessages(enJson, fullNamespaces = FULL_NAMESPACES, picked = PICKED_KEYS) {
    const out = {};
    for (const namespace of fullNamespaces) {
        const section = enJson[namespace];
        if (!section || typeof section !== "object") throw new Error(`en.json is missing namespace "${namespace}"`);
        out[namespace] = flatStrings(namespace, section);
    }
    for (const [namespace, keys] of Object.entries(picked)) {
        const section = enJson[namespace] ?? {};
        out[namespace] = {};
        for (const key of keys) {
            if (typeof section[key] !== "string") throw new Error(`en.json is missing ${namespace}.${key}`);
            out[namespace][key] = section[key];
        }
    }
    return out;
}

export function mergeOverrides(base, overrides) {
    const out = structuredClone(base);
    for (const [namespace, entries] of Object.entries(overrides)) {
        out[namespace] = { ...(out[namespace] ?? {}), ...entries };
    }
    return out;
}

export function renderModule(messages) {
    return [
        "// GENERATED by scripts/extract-timeline-messages.mjs from opennan frontend messages/en.json",
        "// plus src/i18n/en-overrides.json. Do not edit by hand: edit the overrides and re-run.",
        `export const en = ${JSON.stringify(messages, null, 4)} as const;`,
        "",
        "export type TimelineNamespace = keyof typeof en;",
        "",
        "export type TimelineMessages = { [N in TimelineNamespace]: { [K in keyof (typeof en)[N]]: string } };",
        "",
        "export const TIMELINE_NAMESPACES = Object.keys(en) as TimelineNamespace[];",
        "",
    ].join("\n");
}

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
    const check = process.argv.includes("--check");
    const frontend = process.env.OPENNAN_FRONTEND ?? path.resolve(ROOT, "../opennan/frontend");
    const enPath = path.join(frontend, "messages/en.json");
    const outPath = path.join(ROOT, "packages/timeline-react/src/i18n/en.ts");
    const overridesPath = path.join(ROOT, "packages/timeline-react/src/i18n/en-overrides.json");
    if (!fs.existsSync(enPath)) {
        if (check) {
            console.log("extract-timeline-messages: source not found, check skipped");
            process.exit(0);
        }
        console.error(`Source not found: ${enPath} (set OPENNAN_FRONTEND)`);
        process.exit(1);
    }
    const overrides = fs.existsSync(overridesPath) ? JSON.parse(fs.readFileSync(overridesPath, "utf8")) : {};
    const messages = mergeOverrides(pickMessages(JSON.parse(fs.readFileSync(enPath, "utf8"))), overrides);
    const out = renderModule(messages);
    if (check) {
        const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
        if (current !== out) {
            console.error("src/i18n/en.ts is stale: run node scripts/extract-timeline-messages.mjs");
            process.exit(1);
        }
        console.log("src/i18n/en.ts is up to date");
    } else {
        fs.mkdirSync(path.dirname(outPath), { recursive: true });
        fs.writeFileSync(outPath, out);
        const count = Object.values(messages).reduce((sum, section) => sum + Object.keys(section).length, 0);
        console.log(`Wrote ${count} messages in ${Object.keys(messages).length} namespaces to packages/timeline-react/src/i18n/en.ts`);
    }
}
