// Keeps packages/mcp-schema/src/opennan-tool-names.ts in sync with the tool
// names of the private OpenNan chat toolset. Only names are written: no
// descriptions, prompts, or parameters leave the private repo (spec §2.1, §5.7).
// --check also flags tool descriptions that share a long phrase with the OpenNan
// description of the same tool; it prints our phrase and the tool name only.
// Usage: node scripts/opennan-tool-names.mjs [--check] [--require-source]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "packages/mcp-schema/src/opennan-tool-names.ts");
const SCHEMA_DIST = path.join(ROOT, "packages/mcp-schema/dist/index.js");
const SOURCE = process.env.OPENNAN_CHAT_TOOLS ?? path.resolve(ROOT, "../opennan/backend/app/services/chat_ai.py");
const PHRASE_WORDS = 5;

/** Tool names in CHAT_TOOLS order. Accepts `_t("name", ...)` rows and `{"function": {"name": ...}}` dicts. */
export function parseChatToolNames(source) {
    const lines = source.split("\n");
    const start = lines.findIndex((line) => /^CHAT_TOOLS = \[/.test(line));
    if (start < 0) throw new Error("CHAT_TOOLS list not found");
    const end = lines.findIndex((line, i) => i > start && /^\]/.test(line));
    if (end < 0) throw new Error("CHAT_TOOLS list is not closed");
    const names = [];
    for (let i = start + 1; i < end; i += 1) {
        const row = /^\s*_t\("([a-z0-9_]+)"/.exec(lines[i]);
        if (row) names.push(row[1]);
        if (/"function": \{\s*$/.test(lines[i])) {
            const fn = /^\s*"name": "([a-z0-9_]+)"/.exec(lines[i + 1] ?? "");
            if (fn) names.push(fn[1]);
        }
    }
    const seen = new Set();
    for (const name of names) {
        if (seen.has(name)) throw new Error(`duplicate tool name ${name}`);
        seen.add(name);
    }
    return names;
}

export function renderToolNamesModule(names) {
    return [
        "// Generated by scripts/opennan-tool-names.mjs from the OpenNan chat toolset (names only). Do not edit.",
        "export const OPENNAN_TOOL_NAMES = [",
        ...names.map((name) => `    "${name}",`),
        "] as const;",
        "",
        "export type OpenNanToolName = (typeof OPENNAN_TOOL_NAMES)[number];",
        "",
    ].join("\n");
}

/** Python tokens of the CHAT_TOOLS list: string literals (adjacent ones joined, as Python does), names, punctuation. */
function tokenize(source) {
    const start = source.search(/^CHAT_TOOLS = \[/m);
    if (start < 0) throw new Error("CHAT_TOOLS list not found");
    const tokens = [];
    let depth = 0;
    for (let i = source.indexOf("[", start); i < source.length; ) {
        const ch = source[i];
        if (ch === "#") {
            while (i < source.length && source[i] !== "\n") i += 1;
        } else if (/\s/.test(ch)) {
            i += 1;
        } else if (ch === '"' || ch === "'") {
            let value = "";
            i += 1;
            while (i < source.length && source[i] !== ch) {
                if (source[i] === "\\") {
                    value += source[i + 1] === "n" ? " " : source[i + 1];
                    i += 2;
                } else {
                    value += source[i];
                    i += 1;
                }
            }
            i += 1;
            // Whitespace and comments push no token, so a string right after a string is adjacent.
            const last = tokens[tokens.length - 1];
            if (last?.kind === "str") last.value += value;
            else tokens.push({ kind: "str", value });
        } else if (/[A-Za-z_]/.test(ch)) {
            const name = /^[A-Za-z_][A-Za-z0-9_]*/.exec(source.slice(i))[0];
            tokens.push({ kind: "name", value: name });
            i += name.length;
        } else {
            tokens.push({ kind: "punct", value: ch });
            if ("([{".includes(ch)) depth += 1;
            if (")]}".includes(ch)) depth -= 1;
            i += 1;
            if (depth === 0) break;
        }
    }
    return tokens;
}

/**
 * Tool name -> every description text OpenNan has for it: the tool description and the
 * argument notes (`_p(type, note)`, `"description": note`). For the local paraphrase
 * check only; never written to disk.
 */
export function parseChatToolDescriptions(source) {
    const tokens = tokenize(source);
    const descriptions = new Map();
    let tool = null;
    const add = (text) => {
        if (tool && text) descriptions.get(tool).push(text);
    };
    const isStr = (t) => t?.kind === "str";
    const is = (t, value) => t?.value === value && t.kind !== "str";
    for (let i = 0; i < tokens.length; i += 1) {
        const t = tokens[i];
        // _t("name", "description", {...})
        if (t.kind === "name" && t.value === "_t" && is(tokens[i + 1], "(") && isStr(tokens[i + 2])) {
            tool = tokens[i + 2].value;
            descriptions.set(tool, []);
            if (is(tokens[i + 3], ",") && isStr(tokens[i + 4])) add(tokens[i + 4].value);
            continue;
        }
        // "function": { "name": "tool", ...
        if (isStr(t) && t.value === "function" && is(tokens[i + 1], ":") && is(tokens[i + 2], "{")
            && isStr(tokens[i + 3]) && tokens[i + 3].value === "name" && is(tokens[i + 4], ":") && isStr(tokens[i + 5])) {
            tool = tokens[i + 5].value;
            descriptions.set(tool, []);
            continue;
        }
        // "description": "text"   or   "description": ("text" "text")
        if (isStr(t) && t.value === "description" && is(tokens[i + 1], ":")) {
            const value = is(tokens[i + 2], "(") ? tokens[i + 3] : tokens[i + 2];
            if (isStr(value)) add(value.value);
            continue;
        }
        // _p("type", "note", ...)
        if (t.kind === "name" && t.value === "_p" && is(tokens[i + 1], "(") && isStr(tokens[i + 2]) && is(tokens[i + 3], ",") && isStr(tokens[i + 4])) {
            add(tokens[i + 4].value);
        }
    }
    return descriptions;
}

const words = (text) => text.toLowerCase().match(/[a-z0-9]+/g) ?? [];

/** Runs of `n` words that appear in both texts, in the order they appear in `ours`. */
export function sharedPhrases(ours, theirs, n = PHRASE_WORDS) {
    const grams = (list) => list.slice(0, Math.max(0, list.length - n + 1)).map((_word, i) => list.slice(i, i + n).join(" "));
    const other = new Set(grams(words(theirs)));
    return [...new Set(grams(words(ours)).filter((gram) => other.has(gram)))];
}

/** Our tool description and every argument description in its input schema (nested ones too). */
export function ourDescriptions(tool) {
    const texts = [{ where: "description", text: tool.description }];
    const visit = (schema, where) => {
        if (!schema || typeof schema !== "object") return;
        if (where && typeof schema.description === "string") texts.push({ where, text: schema.description });
        for (const [key, child] of Object.entries(schema.properties ?? {})) visit(child, where ? `${where}.${key}` : key);
        if (schema.items) visit(schema.items, `${where}[]`);
        for (const branch of schema.anyOf ?? []) visit(branch, where);
    };
    visit(tool.inputSchema, "");
    return texts;
}

async function checkDescriptions(sourceText) {
    if (!fs.existsSync(SCHEMA_DIST)) {
        console.warn("opennan-tool-names: WARNING packages/mcp-schema/dist is missing, descriptions NOT checked (run pnpm build first)");
        return true;
    }
    const { STUDIO_TOOLS } = await import(pathToFileURL(SCHEMA_DIST).href);
    // Between Task 9 and Task 10 the built entry exports only renderCoverageMarkdown.
    if (!Array.isArray(STUDIO_TOOLS)) {
        console.warn("opennan-tool-names: WARNING the built @opennan/mcp-schema exports no STUDIO_TOOLS yet, descriptions NOT checked");
        return true;
    }
    const theirs = parseChatToolDescriptions(sourceText);
    let clean = true;
    for (const tool of STUDIO_TOOLS) {
        for (const ours of ourDescriptions(tool)) {
            for (const text of theirs.get(tool.name) ?? []) {
                const shared = sharedPhrases(ours.text, text);
                if (shared.length === 0) continue;
                clean = false;
                console.error(`opennan-tool-names: ${tool.name} ${ours.where} repeats OpenNan wording: "${shared[0]}" (reword it)`);
                break;
            }
        }
    }
    return clean;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const check = process.argv.includes("--check");
    if (!fs.existsSync(SOURCE)) {
        if (check && !process.argv.includes("--require-source")) {
            console.warn("opennan-tool-names: WARNING OpenNan chat_ai.py not found; tool names and descriptions were NOT checked.");
            console.warn("opennan-tool-names: the private CI job runs this check with OPENNAN_CHAT_TOOLS set (spec §2.1).");
            process.exit(0);
        }
        console.error(`Source not found: ${SOURCE} (set OPENNAN_CHAT_TOOLS)`);
        process.exit(1);
    }
    const sourceText = fs.readFileSync(SOURCE, "utf8");
    const text = renderToolNamesModule(parseChatToolNames(sourceText));
    if (check) {
        const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
        if (current !== text) {
            console.error("opennan-tool-names.ts is out of date: run pnpm tools:names");
            process.exit(1);
        }
        if (!(await checkDescriptions(sourceText))) process.exit(1);
        console.log("opennan-tool-names: up to date");
    } else {
        fs.writeFileSync(OUT, text);
        console.log(`opennan-tool-names: wrote ${text.split("\n").filter((l) => l.startsWith("    \"")).length} names`);
    }
}
