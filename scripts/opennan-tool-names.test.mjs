import { test } from "node:test";
import assert from "node:assert/strict";
import { parseChatToolDescriptions, parseChatToolNames, renderToolNamesModule, sharedPhrases } from "./opennan-tool-names.mjs";

const SOURCE = [
    "X = 1",
    "CHAT_TOOLS = [",
    "    {",
    "        \"type\": \"function\",",
    "        \"function\": {",
    "            \"name\": \"create_scenes\",",
    "            \"parameters\": {\"properties\": {\"name\": _p(\"string\", \"x\")}},",
    "        },",
    "    },",
    "    _t(\"read_timeline\", \"d\", {}, req=[]),",
    "    _t(\"find_clip\", \"d\", {",
    "        \"name\": _p(\"string\", \"not a tool\"),",
    "    }),",
    "]",
    "OTHER = [_t(\"not_listed\", \"d\", {})]",
].join("\n");

test("reads tool names in list order and ignores parameters named name", () => {
    assert.deepEqual(parseChatToolNames(SOURCE), ["create_scenes", "read_timeline", "find_clip"]);
});

test("rejects duplicates and a missing list", () => {
    assert.throws(() => parseChatToolNames(SOURCE.replace("find_clip", "read_timeline")), /duplicate tool name read_timeline/);
    assert.throws(() => parseChatToolNames("x = []"), /CHAT_TOOLS list not found/);
});

test("renders a typed module", () => {
    assert.equal(
        renderToolNamesModule(["a_b"]),
        "// Generated by scripts/opennan-tool-names.mjs from the OpenNan chat toolset (names only). Do not edit.\n"
            + "export const OPENNAN_TOOL_NAMES = [\n    \"a_b\",\n] as const;\n\nexport type OpenNanToolName = (typeof OPENNAN_TOOL_NAMES)[number];\n",
    );
});

test("finds descriptions and the long phrases two descriptions share", () => {
    const descriptions = parseChatToolDescriptions(SOURCE);
    assert.deepEqual(descriptions.get("read_timeline"), ["d"]);
    assert.deepEqual(descriptions.get("create_scenes"), ["x"]);
    assert.deepEqual(descriptions.get("find_clip"), ["d", "not a tool"]);
    assert.deepEqual(
        sharedPhrases("Scores the video on sharpness and exposure today.", "It scores the video on sharpness and noise.", 5),
        ["scores the video on sharpness", "the video on sharpness and"],
    );
    assert.deepEqual(sharedPhrases("a b c", "a b c", 5), []);
});

test("joins descriptions split over several string literals, also for arguments", () => {
    const split = [
        "CHAT_TOOLS = [",
        "    _t(\"split_tool\",",
        "       \"First part of the text \"",
        "       \"and the second part.\", {",
        "        \"arg\": _p(\"string\", \"An argument note \"",
        "            'that wraps.'),",
        "    }),",
        "    {",
        "        \"function\": {",
        "            \"name\": \"dict_tool\",",
        "            \"description\": (\"Opens with this \"  # a comment",
        "                \"and ends here.\"),",
        "        },",
        "    },",
        "]",
    ].join("\n");
    const descriptions = parseChatToolDescriptions(split);
    assert.deepEqual(descriptions.get("split_tool"), ["First part of the text and the second part.", "An argument note that wraps."]);
    assert.deepEqual(descriptions.get("dict_tool"), ["Opens with this and ends here."]);
});
